//! A hidden top-level window receives TaskbarCreated broadcasts. Message-only
//! windows do not. Wndproc only forwards presentation events, never core commands.
use crate::{
    AppState, MainWindow, QueueHistoryState,
    notifications::{NoticeQueue, Summary},
};
use slint::{ComponentHandle, Timer, TimerMode};
use std::{
    cell::{Cell, RefCell},
    rc::Rc,
    sync::mpsc,
    time::{Duration, Instant},
};
use windows::{
    Win32::{
        Foundation::{HWND, LPARAM, LRESULT, POINT, WPARAM},
        System::LibraryLoader::GetModuleHandleW,
        UI::{
            Shell::{
                NIF_ICON, NIF_INFO, NIF_MESSAGE, NIF_TIP, NIIF_INFO, NIIF_RESPECT_QUIET_TIME,
                NIIF_WARNING, NIM_ADD, NIM_DELETE, NIM_MODIFY, NIN_BALLOONHIDE, NIN_BALLOONTIMEOUT,
                NIN_BALLOONUSERCLICK, NOTIFYICONDATAW, Shell_NotifyIconW,
            },
            WindowsAndMessaging::*,
        },
    },
    core::{HSTRING, PCWSTR, w},
};

const CALLBACK: u32 = WM_APP + 24;
const OPEN: usize = 1;
const EXIT: usize = 2;
#[derive(Clone, Copy)]
enum Event {
    Open,
    Exit,
    ShellRestart,
    History,
    NoticeClosed,
}

struct State {
    hwnd: HWND,
    icon: HICON,
    taskbar_created: u32,
    events: mpsc::Sender<Event>,
    status: RefCell<String>,
    notices: RefCell<NoticeQueue>,
    notice_visible: Cell<bool>,
}

impl State {
    fn data(&self, tooltip: &str) -> NOTIFYICONDATAW {
        let mut data = NOTIFYICONDATAW {
            cbSize: std::mem::size_of::<NOTIFYICONDATAW>() as u32,
            hWnd: self.hwnd,
            uID: 1,
            uFlags: NIF_ICON | NIF_MESSAGE | NIF_TIP,
            uCallbackMessage: CALLBACK,
            hIcon: self.icon,
            ..Default::default()
        };
        for (dest, src) in data.szTip.iter_mut().take(127).zip(tooltip.encode_utf16()) {
            *dest = src;
        }
        data
    }

    fn show_notice(&self, summary: Summary) -> bool {
        let mut data = self.data("");
        data.uFlags = NIF_INFO;
        data.dwInfoFlags = (if summary.failed > 0 {
            NIIF_WARNING
        } else {
            NIIF_INFO
        }) | NIIF_RESPECT_QUIET_TIME;
        let title = if summary.failed > 0 {
            "Stream Archive 다운로드 결과"
        } else {
            "Stream Archive 다운로드 완료"
        };
        let body = format!(
            "VOD 완료 {}건 · 실패 {}건\n클릭하면 History에서 결과를 확인합니다.",
            summary.completed, summary.failed
        );
        for (dest, src) in data
            .szInfoTitle
            .iter_mut()
            .take(63)
            .zip(title.encode_utf16())
        {
            *dest = src;
        }
        for (dest, src) in data.szInfo.iter_mut().take(255).zip(body.encode_utf16()) {
            *dest = src;
        }
        let shown = unsafe { Shell_NotifyIconW(NIM_MODIFY, &data).as_bool() };
        self.notice_visible.set(shown);
        shown
    }

    fn clear_notice(&self) {
        self.notices.borrow_mut().clear();
        if self.notice_visible.replace(false) {
            let mut data = self.data("");
            data.uFlags = NIF_INFO;
            let _ = unsafe { Shell_NotifyIconW(NIM_MODIFY, &data) };
        }
    }

    fn ensure(&self, tooltip: &str) -> bool {
        let data = self.data(tooltip);
        // Verify the icon still exists, or re-add it after Explorer restarts.
        unsafe {
            Shell_NotifyIconW(NIM_MODIFY, &data).as_bool()
                || Shell_NotifyIconW(NIM_ADD, &data).as_bool()
        }
    }
}

struct Tray {
    state: *mut State,
}
impl Tray {
    fn state(&self) -> &State {
        // SAFETY: `self.state` is allocated with `Box::into_raw` in `Tray::new` and only
        // freed in `Drop` after `GWLP_USERDATA` is cleared and the hidden window is destroyed.
        unsafe { &*self.state }
    }

    fn new(events: mpsc::Sender<Event>) -> Result<Self, String> {
        // Native resources and callbacks stay on the Slint UI thread.
        unsafe {
            let module = GetModuleHandleW(None).map_err(|e| e.to_string())?;
            let class = w!("StreamArchiveTrayWindow");
            let wc = WNDCLASSW {
                lpfnWndProc: Some(wndproc),
                hInstance: module.into(),
                lpszClassName: class,
                ..Default::default()
            };
            // An existing class is harmless; CreateWindowExW reports real errors.
            let _ = RegisterClassW(&wc);
            let hwnd = CreateWindowExW(
                WS_EX_TOOLWINDOW,
                class,
                w!("Stream Archive tray"),
                WINDOW_STYLE(0),
                0,
                0,
                0,
                0,
                None,
                None,
                Some(module.into()),
                None,
            )
            .map_err(|e| e.to_string())?;
            // Resource 1 is the existing multi-frame icon generated by build.rs.
            let icon = match LoadImageW(
                Some(module.into()),
                PCWSTR(std::ptr::without_provenance(1)),
                IMAGE_ICON,
                32,
                32,
                IMAGE_FLAGS(0),
            ) {
                Ok(handle) => HICON(handle.0),
                Err(error) => {
                    let _ = DestroyWindow(hwnd);
                    return Err(error.to_string());
                }
            };
            let taskbar_created = RegisterWindowMessageW(w!("TaskbarCreated"));
            if taskbar_created == 0 {
                let _ = DestroyIcon(icon);
                let _ = DestroyWindow(hwnd);
                return Err("TaskbarCreated message registration failed".into());
            }
            let state = Box::into_raw(Box::new(State {
                hwnd,
                icon,
                taskbar_created,
                status: RefCell::new("상태 확인 중".into()),
                notices: RefCell::new(NoticeQueue::default()),
                notice_visible: Cell::new(false),
                events,
            }));
            SetWindowLongPtrW(hwnd, GWLP_USERDATA, state as isize);
            let tray = Self { state };
            if !tray.state().ensure("Stream Archive") {
                return Err("Windows 트레이 아이콘 등록 실패".into());
            }
            Ok(tray)
        }
    }
}
impl Drop for Tray {
    fn drop(&mut self) {
        unsafe {
            let state = &*self.state;
            let hwnd = state.hwnd;
            let icon = state.icon;
            // Clear GWLP_USERDATA before Shell_NotifyIconW/DestroyWindow so re-entrant
            // window messages during teardown cannot observe a freeing State pointer.
            SetWindowLongPtrW(hwnd, GWLP_USERDATA, 0);
            let _ = Shell_NotifyIconW(NIM_DELETE, &state.data(""));
            let _ = DestroyWindow(hwnd);
            let _ = DestroyIcon(icon);
            drop(Box::from_raw(self.state));
        }
    }
}

unsafe extern "system" fn wndproc(
    hwnd: HWND,
    message: u32,
    wparam: WPARAM,
    lparam: LPARAM,
) -> LRESULT {
    let ptr = unsafe { GetWindowLongPtrW(hwnd, GWLP_USERDATA) } as *const State;
    if !ptr.is_null() {
        // Box is stable until Drop clears USERDATA before destroying HWND.
        let state = unsafe { &*ptr };
        if message == state.taskbar_created {
            let _ = state.events.send(Event::ShellRestart);
            return LRESULT(0);
        }
        if message == CALLBACK {
            match lparam.0 as u32 {
                NIN_BALLOONUSERCLICK => {
                    let _ = state.events.send(Event::History);
                    let _ = state.events.send(Event::NoticeClosed);
                }
                NIN_BALLOONHIDE | NIN_BALLOONTIMEOUT => {
                    let _ = state.events.send(Event::NoticeClosed);
                }
                WM_LBUTTONUP => {
                    let _ = state.events.send(Event::Open);
                }
                WM_RBUTTONUP | WM_CONTEXTMENU => unsafe {
                    popup(state);
                },
                _ => {}
            }
            return LRESULT(0);
        }
    }
    unsafe { DefWindowProcW(hwnd, message, wparam, lparam) }
}

unsafe fn popup(state: &State) {
    unsafe {
        let Ok(menu) = CreatePopupMenu() else { return };
        let _ = AppendMenuW(menu, MF_STRING, OPEN, w!("Stream Archive 열기"));
        let label = HSTRING::from(state.status.borrow().as_str());
        let _ = AppendMenuW(menu, MF_STRING | MF_GRAYED, 3, &label);
        let _ = AppendMenuW(menu, MF_SEPARATOR, 0, PCWSTR::null());
        let _ = AppendMenuW(menu, MF_STRING, EXIT, w!("종료"));
        let mut point = POINT::default();
        if GetCursorPos(&mut point).is_ok() {
            let _ = SetForegroundWindow(state.hwnd);
            let command = TrackPopupMenu(
                menu,
                TPM_RETURNCMD | TPM_RIGHTBUTTON,
                point.x,
                point.y,
                None,
                state.hwnd,
                None,
            )
            .0 as usize;
            let _ = PostMessageW(Some(state.hwnd), WM_NULL, WPARAM(0), LPARAM(0));
            match command {
                OPEN => {
                    let _ = state.events.send(Event::Open);
                }
                EXIT => {
                    let _ = state.events.send(Event::Exit);
                }
                _ => {}
            }
        }
        let _ = DestroyMenu(menu);
    }
}

pub struct Desktop {
    _timer: Timer,
    _tray: Rc<Option<Tray>>,
}

fn apply_native_window_icon(window: &slint::winit_030::winit::window::Window) {
    use slint::winit_030::winit::raw_window_handle::{HasWindowHandle, RawWindowHandle};
    let Ok(handle) = window.window_handle() else {
        return;
    };
    let RawWindowHandle::Win32(handle) = handle.as_raw() else {
        return;
    };
    let hwnd = HWND(handle.hwnd.get() as *mut _);
    unsafe {
        let Ok(module) = GetModuleHandleW(None) else {
            return;
        };
        if let Ok(small) = LoadImageW(
            Some(module.into()),
            PCWSTR(std::ptr::without_provenance(1)),
            IMAGE_ICON,
            16,
            16,
            LR_SHARED,
        ) {
            let _ = SendMessageW(
                hwnd,
                WM_SETICON,
                Some(WPARAM(ICON_SMALL as usize)),
                Some(LPARAM(small.0 as isize)),
            );
        }
        if let Ok(big) = LoadImageW(
            Some(module.into()),
            PCWSTR(std::ptr::without_provenance(1)),
            IMAGE_ICON,
            32,
            32,
            LR_SHARED,
        ) {
            let _ = SendMessageW(
                hwnd,
                WM_SETICON,
                Some(WPARAM(ICON_BIG as usize)),
                Some(LPARAM(big.0 as isize)),
            );
        }
    }
}

fn apply_restored_window_chrome(ui: &MainWindow, restore_maximized: bool) -> bool {
    if !ui.window().is_visible() {
        return true;
    }
    use slint::winit_030::{WinitWindowAccessor, winit::dpi};
    let mut applied = false;
    ui.window().with_winit_window(|window| {
        applied = true;
        // Un-minimize before inspecting bounds; Win32 reports (-32000, -32000) / (0, 0) while minimized.
        window.set_minimized(false);
        window.set_min_inner_size(Some(dpi::LogicalSize::new(1000.0_f64, 650.0_f64)));
        if let Ok(pos) = window.outer_position()
            && (pos.x <= -10_000 || pos.y <= -10_000)
        {
            window.set_outer_position(dpi::LogicalPosition::new(120.0_f64, 80.0_f64));
        }
        let size = window.inner_size();
        if size.width < 200 || size.height < 200 {
            let _ = window.request_inner_size(dpi::LogicalSize::new(1120.0_f64, 720.0_f64));
        }
        apply_native_window_icon(window);
        if restore_maximized {
            window.set_maximized(true);
        }
        window.set_visible(true);
        window.focus_window();
        window.request_redraw();
    });
    if applied {
        ui.window().set_minimized(false);
        ui.window().request_redraw();
    }
    applied
}

static RESTORE_GENERATION: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(1);

fn schedule_restore_chrome_retry(
    weak: slint::Weak<MainWindow>,
    restore_maximized: bool,
    generation: u64,
    remaining: u32,
) {
    if remaining == 0 {
        return;
    }
    Timer::single_shot(Duration::from_millis(60), move || {
        if RESTORE_GENERATION.load(std::sync::atomic::Ordering::Acquire) != generation {
            return;
        }
        let Some(ui) = weak.upgrade() else {
            return;
        };
        if !apply_restored_window_chrome(&ui, restore_maximized) {
            schedule_restore_chrome_retry(weak, restore_maximized, generation, remaining - 1);
        }
    });
}

pub fn sync_recreated_window(ui: &MainWindow, restore_maximized: bool) {
    let generation = RESTORE_GENERATION.fetch_add(1, std::sync::atomic::Ordering::AcqRel) + 1;
    if apply_restored_window_chrome(ui, restore_maximized) {
        return;
    }
    // Retry for up to ~2.4s to handle slower wgpu/TDR window recreation after driver resets.
    schedule_restore_chrome_retry(ui.as_weak(), restore_maximized, generation, 40);
}

fn restore(ui: &MainWindow, hidden_maximized: &Cell<bool>) {
    let was_hidden = !ui.window().is_visible();
    let restore_maximized = if was_hidden {
        hidden_maximized.replace(false)
    } else {
        false
    };
    if let Err(error) = ui.show() {
        crate::append_gui_crash_log(&format!("tray restore ui.show failed: {error}"));
    }
    ui.window().set_minimized(false);
    sync_recreated_window(ui, restore_maximized);
    ui.window().request_redraw();
}

pub fn bind(ui: &MainWindow) -> Desktop {
    let (events, receiver) = mpsc::channel();
    let tray = Rc::new(match Tray::new(events) {
        Ok(tray) => Some(tray),
        Err(error) => {
            ui.global::<AppState>()
                .set_desktop_status(format!("트레이 사용 불가: {error}").into());
            None
        }
    });
    let clear_tray = tray.clone();
    ui.global::<AppState>().on_clear_download_notices(move || {
        if let Some(tray) = clear_tray.as_ref().as_ref() {
            tray.state().clear_notice();
        }
    });
    let weak = ui.as_weak();
    let notice_tray = tray.clone();
    ui.global::<AppState>()
        .on_download_notice(move |completed, failed| {
            let Some(ui) = weak.upgrade() else { return };
            let state = ui.global::<AppState>();
            if !state.get_download_notifications_enabled() || state.get_desktop_exit_pending() {
                return;
            }
            if let Some(tray) = notice_tray.as_ref().as_ref() {
                tray.state()
                    .notices
                    .borrow_mut()
                    .add(Summary { completed, failed }, Instant::now());
            } else {
                state.set_download_notifications_status(
                    "트레이 등록 실패로 알림을 표시하지 못했습니다. History에서 결과를 확인하세요."
                        .into(),
                );
            }
        });
    let weak = ui.as_weak();
    let apply_tray = tray.clone();
    let informed = Cell::new(false);
    let hidden_maximized = Rc::new(Cell::new(false));
    let hide_maximized = hidden_maximized.clone();
    ui.global::<AppState>().on_close_apply(move |action| {
        let Some(ui) = weak.upgrade() else { return };
        let state = ui.global::<AppState>();
        if state.get_desktop_exit_pending() {
            return;
        }
        if action == "TRAY" {
            if let Some(tray) = apply_tray.as_ref().as_ref()
                && tray
                    .state()
                    .ensure(&format!("Stream Archive — {}", state.get_desktop_status()))
            {
                if !informed.get() {
                    super::notify(&ui, "창을 닫아도 녹화·다운로드·채널 감시가 계속 실행됩니다.\n앱을 종료하려면 트레이 메뉴의 ‘종료’를 선택하세요.");
                }
                // Explorer may restart while the information dialog is open.
                if tray
                    .state()
                    .ensure(&format!("Stream Archive — {}", state.get_desktop_status()))
                {
                    hide_maximized.set(ui.window().is_maximized());
                    match ui.hide() {
                        Ok(()) => {
                            informed.set(true);
                            state.set_close_dialog_visible(false);
                        }
                        Err(error) => {
                            state.set_close_choice_error(format!("창을 숨기지 못했습니다: {error}").into());
                            state.set_close_dialog_visible(true);
                        }
                    }
                } else {
                    state.set_close_choice_error("트레이 아이콘을 등록하지 못해 창을 유지합니다.".into());
                    state.set_close_dialog_visible(true);
                }
            } else {
                state.set_close_choice_error(
                    "트레이 아이콘을 등록하지 못해 창을 유지합니다.".into(),
                );
                state.set_close_dialog_visible(true);
            }
        } else if action == "EXIT" {
            state.set_close_dialog_visible(false);
            state.invoke_desktop_exit();
        }
    });
    let weak = ui.as_weak();
    ui.window().on_close_requested(move || {
        let Some(ui) = weak.upgrade() else {
            return slint::CloseRequestResponse::KeepWindowShown;
        };
        let state = ui.global::<AppState>();
        if super::close_request_blocked(
            state.get_settings_loaded(),
            state.get_settings_busy(),
            state.get_close_choice_busy(),
            state.get_close_dialog_visible(),
            state.get_desktop_exit_pending(),
        ) {
            return slint::CloseRequestResponse::KeepWindowShown;
        }
        if state.get_close_action() == "ASK" {
            state.set_close_remember(false);
            state.set_close_choice_error("".into());
            state.set_close_dialog_visible(true);
        } else {
            state.invoke_close_apply(state.get_close_action());
        }
        slint::CloseRequestResponse::KeepWindowShown
    });
    let weak = ui.as_weak();
    let timer_tray = tray.clone();
    let timer = Timer::default();
    let mut last_poll = Instant::now();
    let mut last_tray_sync = Instant::now();
    let mut last_tooltip = String::from("Stream Archive");
    let mut recovery = super::TrayRecovery::default();
    timer.start(TimerMode::Repeated, Duration::from_millis(100), move || {
        let Some(ui) = weak.upgrade() else { return };
        let state = ui.global::<AppState>();
        let mut recover = false;
        while let Ok(event) = receiver.try_recv() {
            match event {
                Event::Open => restore(&ui, &hidden_maximized),
                Event::Exit => {
                    restore(&ui, &hidden_maximized);
                    state.invoke_desktop_exit();
                }
                Event::ShellRestart => {
                    recover = true;
                    if let Some(tray) = timer_tray.as_ref().as_ref() {
                        tray.state().notice_visible.set(false);
                        tray.state().notices.borrow_mut().closed();
                    }
                }
                Event::NoticeClosed => {
                    if let Some(tray) = timer_tray.as_ref().as_ref() {
                        tray.state().notice_visible.set(false);
                        tray.state().notices.borrow_mut().closed();
                    }
                }
                Event::History => {
                    restore(&ui, &hidden_maximized);
                    state.set_active_page("History".into());
                    let history = ui.global::<QueueHistoryState>();
                    history.set_history_view("VOD".into());
                    history.set_history_search("".into());
                    history.set_history_status("".into());
                    history.set_history_from_date("".into());
                    history.set_history_to_date("".into());
                    history.set_history_limit("100".into());
                    history.invoke_history_refresh();
                }
            }
        }
        if let Some(tray) = timer_tray.as_ref().as_ref() {
            if !state.get_download_notifications_enabled() || state.get_desktop_exit_pending() {
                tray.state().clear_notice();
            } else {
                let summary = tray.state().notices.borrow_mut().take(Instant::now());
                if let Some(summary) = summary {
                    // Best effort only; never block downloads or show a modal error.
                    let tip = format!("Stream Archive — {}", state.get_desktop_status());
                    if !tray.state().ensure(&tip) || !tray.state().show_notice(summary) {
                        tray.state().notices.borrow_mut().closed();
                        state.set_download_notifications_status(
                            "Windows 알림 전송 실패. History에서 결과를 확인하세요.".into(),
                        );
                    } else {
                        last_tooltip = tip;
                        last_tray_sync = Instant::now();
                        state.set_download_notifications_status("".into());
                    }
                }
            }
        }
        if recover || last_poll.elapsed() >= Duration::from_secs(2) {
            last_poll = Instant::now();
            if !state.get_desktop_exit_pending() {
                state.invoke_desktop_poll();
            }
            if let Some(tray) = timer_tray.as_ref().as_ref() {
                let desktop_status = state.get_desktop_status().to_string();
                *tray.state().status.borrow_mut() = desktop_status.clone();
                let tip = format!("Stream Archive — {desktop_status}");
                let visible = ui.window().is_visible();
                let need_tray_ipc = recover
                    || tip != last_tooltip
                    || (!visible && last_tray_sync.elapsed() >= Duration::from_secs(20));
                if need_tray_ipc {
                    last_tray_sync = Instant::now();
                    let registered = tray.state().ensure(&tip);
                    if registered {
                        last_tooltip = tip;
                    }
                    if !state.get_desktop_exit_pending()
                        && recovery.should_restore(registered, visible)
                    {
                        restore(&ui, &hidden_maximized);
                        // A synchronous MessageBox here holds the Slint timer
                        // callback open after show(), delaying the first repaint.
                        state.set_desktop_recovery_message(
                            "Windows 트레이를 복구하지 못해 창을 다시 표시했습니다. 녹화·다운로드는 계속 실행됩니다.".into());
                        crate::append_gui_crash_log(
                            "[DESKTOP:WARN] Windows tray registration failed repeatedly; restoring window",
                        );
                    }
                }
            }
        }
    });
    Desktop {
        _timer: timer,
        _tray: tray,
    }
}
