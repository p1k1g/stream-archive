fn redact(text: &str) -> String {
    let re = Regex::new(
        r"(?i)(cookie|token|signature|policy|key-pair-id|authorization)(\s*[:=]\s*)[^\s;&]+",
    )
    .unwrap();
    let safe = re.replace_all(text, "$1$2***");
    Regex::new(r"(?i)(https?://[^?\s]+)\?[^\s]+")
        .unwrap()
        .replace_all(&safe, "$1?[REDACTED]")
        .to_string()
}

