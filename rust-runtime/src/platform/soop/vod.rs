#[derive(Debug, Clone)]
struct NetscapeCookie {
    domain: String,
    include_subdomains: bool,
    path: String,
    secure: bool,
    expires: i64,
    name: String,
    value: String,
}

#[derive(Debug, Clone, Default)]
struct CookieJar {
    items: Vec<NetscapeCookie>,
}

impl CookieJar {
    fn parse_file(path: &Path) -> Result<Self> {
        let text = fs::read_to_string(path)
            .with_context(|| format!("Cookie 파일 읽기 실패: {}", path.display()))?;
        let mut items = Vec::new();
        for raw in text.lines() {
            let line = raw.trim_end();
            if line.trim().is_empty() || (line.starts_with('#') && !line.starts_with("#HttpOnly_"))
            {
                continue;
            }
            let normalized = line.strip_prefix("#HttpOnly_").unwrap_or(line);
            let fields: Vec<&str> = normalized.splitn(7, '\t').collect();
            if fields.len() != 7 {
                continue;
            }
            items.push(NetscapeCookie {
                domain: fields[0].to_string(),
                include_subdomains: fields[1].eq_ignore_ascii_case("TRUE"),
                path: fields[2].to_string(),
                secure: fields[3].eq_ignore_ascii_case("TRUE"),
                expires: fields[4].parse().unwrap_or(0),
                name: fields[5].to_string(),
                value: fields[6].to_string(),
            });
        }
        if items.is_empty() {
            bail!("Cookie 파일이 Netscape 형식이 아니거나 비어 있습니다.");
        }
        Ok(Self { items })
    }

    fn write_file(&self, path: &Path) -> Result<()> {
        let mut out = String::from(
            "# Netscape HTTP Cookie File\n# Generated by Stream Archive SOOP VOD; do not share.\n",
        );
        for c in &self.items {
            out.push_str(&format!(
                "{}\t{}\t{}\t{}\t{}\t{}\t{}\n",
                c.domain,
                if c.include_subdomains {
                    "TRUE"
                } else {
                    "FALSE"
                },
                c.path,
                if c.secure { "TRUE" } else { "FALSE" },
                c.expires,
                sanitize_cookie_field(&c.name),
                sanitize_cookie_field(&c.value)
            ));
        }
        fs::write(path, out).with_context(|| format!("Cookie 파일 저장 실패: {}", path.display()))
    }

    fn header_for(&self, url: &str) -> Result<String> {
        let url = Url::parse(url)?;
        let host = url.host_str().unwrap_or("").to_ascii_lowercase();
        let path = url.path();
        let now = Utc::now().timestamp();
        let values = self
            .items
            .iter()
            .filter(|c| {
                if c.expires > 0 && c.expires < now {
                    return false;
                }
                if c.secure && url.scheme() != "https" {
                    return false;
                }
                let domain = c.domain.trim_start_matches('.').to_ascii_lowercase();
                let domain_ok = if c.include_subdomains || c.domain.starts_with('.') {
                    host == domain || host.ends_with(&format!(".{domain}"))
                } else {
                    host == domain
                };
                domain_ok && path.starts_with(if c.path.is_empty() { "/" } else { &c.path })
            })
            .map(|c| format!("{}={}", c.name, c.value))
            .collect::<Vec<_>>();
        Ok(values.join("; "))
    }

    fn upsert(&mut self, cookie: NetscapeCookie) {
        self.items.retain(|c| {
            !(c.name.eq_ignore_ascii_case(&cookie.name)
                && c.domain.eq_ignore_ascii_case(&cookie.domain)
                && c.path == cookie.path)
        });
        self.items.push(cookie);
    }

    fn remove_cloudfront(&mut self) {
        self.items
            .retain(|c| !c.name.to_ascii_lowercase().starts_with("cloudfront-"));
    }

    fn has_cloudfront(&self) -> bool {
        CF_NAMES.iter().all(|name| {
            self.items
                .iter()
                .any(|c| c.name.eq_ignore_ascii_case(name) && !c.value.is_empty())
        })
    }

    fn has_login(&self) -> bool {
        LOGIN_COOKIE_NAMES.iter().any(|name| {
            self.items
                .iter()
                .any(|c| c.name.eq_ignore_ascii_case(name) && !c.value.is_empty())
        })
    }

    fn cloudfront_header(&self) -> Result<String> {
        let mut map = HashMap::new();
        for c in &self.items {
            if CF_NAMES.iter().any(|n| c.name.eq_ignore_ascii_case(n)) {
                map.insert(c.name.to_ascii_lowercase(), c.value.clone());
            }
        }
        let mut parts = Vec::new();
        for name in CF_NAMES {
            let value = map
                .get(&name.to_ascii_lowercase())
                .ok_or_else(|| anyhow!("{name} Cookie가 없습니다."))?;
            parts.push(format!("{name}={value}"));
        }
        Ok(parts.join("; "))
    }

    fn repair_cloudfront_scope(&mut self, manifest_url: &str) -> Result<()> {
        let parsed = Url::parse(manifest_url)?;
        let host = parsed
            .host_str()
            .ok_or_else(|| anyhow!("manifest host 없음"))?
            .to_ascii_lowercase();
        let mut latest: HashMap<String, NetscapeCookie> = HashMap::new();
        let mut keep = Vec::new();
        for c in self.items.drain(..) {
            if c.name.to_ascii_lowercase().starts_with("cloudfront-") {
                latest.insert(c.name.to_ascii_lowercase(), c);
            } else {
                keep.push(c);
            }
        }
        for name in CF_NAMES {
            let mut c = latest
                .remove(&name.to_ascii_lowercase())
                .ok_or_else(|| anyhow!("private_auth 응답에 {name} Cookie가 없습니다."))?;
            c.domain = host.clone();
            c.include_subdomains = false;
            c.path = "/".into();
            c.secure = true;
            keep.push(c);
        }
        self.items = keep;
        Ok(())
    }
}

struct JobRuntime {
    task: Option<JoinHandle<()>>,
    cancel: Arc<AtomicBool>,
}

struct JobDirGuard(PathBuf);
impl Drop for JobDirGuard {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

const TERMINAL_CACHE_LIMIT: usize = 32;

pub struct VodManager {
    backend_dir: PathBuf,
    logs: LogBuffer,
    runtime: Mutex<JobRuntime>,
    status: Arc<RwLock<VodJobStatus>>,
    terminal: Arc<Mutex<VecDeque<(String, VodJobStatus)>>>,
}

impl VodManager {
    pub fn new(backend_dir: PathBuf, logs: LogBuffer) -> Self {
        Self {
            backend_dir,
            logs,
            runtime: Mutex::new(JobRuntime {
                task: None,
                cancel: Arc::new(AtomicBool::new(false)),
            }),
            status: Arc::new(RwLock::new(VodJobStatus::default())),
            terminal: Arc::new(Mutex::new(VecDeque::new())),
        }
    }

    pub async fn status(&self) -> VodJobStatus {
        {
            let mut runtime = self.runtime.lock().await;
            if runtime.task.as_ref().is_some_and(|task| task.is_finished()) {
                runtime.task.take();
            }
        }
        self.status.read().await.clone()
    }

    pub async fn terminal_status(&self, job_id: &str) -> Option<VodJobStatus> {
        let terminal = self.terminal.lock().await;
        terminal
            .iter()
            .rev()
            .find(|(id, _)| id == job_id)
            .map(|(_, status)| status.clone())
    }

    pub async fn analyze(&self, req: VodAnalyzeRequest) -> Result<VodJobStatus> {
        self.start_job(VodJobKind::Analyze(req)).await
    }

    pub async fn download(&self, req: VodDownloadRequest) -> Result<VodJobStatus> {
        self.start_job(VodJobKind::Download(req)).await
    }

    async fn start_job(&self, kind: VodJobKind) -> Result<VodJobStatus> {
        let mut runtime = self.runtime.lock().await;
        if runtime.task.as_ref().is_some_and(|t| !t.is_finished()) {
            bail!("다른 VOD 작업이 이미 실행 중입니다.");
        }
        runtime.task.take();
        let cancel = Arc::new(AtomicBool::new(false));
        runtime.cancel = cancel.clone();
        let backend = self.backend_dir.clone();
        let logs = self.logs.clone();
        let status = self.status.clone();
        let terminal = self.terminal.clone();
        let job_id = Uuid::new_v4().to_string();
        let terminal_job_id = job_id.clone();
        {
            let mut s = status.write().await;
            *s = VodJobStatus {
                state: "STARTING".into(),
                running: true,
                job_id: Some(job_id),
                message: "VOD 작업 준비 중…".into(),
                started_at: Some(Utc::now().to_rfc3339()),
                ..Default::default()
            };
        }
        let task = tokio::spawn(async move {
            let result = match kind {
                VodJobKind::Analyze(req) => run_analysis(&backend, req, &logs, &status, &cancel)
                    .await
                    .map(|_| ()),
                VodJobKind::Download(req) => {
                    run_download(&backend, req, &logs, &status, &cancel).await
                }
            };
            let final_status = {
                let mut s = status.write().await;
                s.running = false;
                s.finished_at = Some(Utc::now().to_rfc3339());
                if cancel.load(Ordering::SeqCst) {
                    s.state = "CANCELLED".into();
                    s.message = "VOD 작업이 취소되었습니다.".into();
                    logs.push("[VOD] job cancelled").await;
                } else if let Err(err) = result {
                    s.state = "FAILED".into();
                    s.message = redact(&format!("{err:#}"));
                    logs.push(format!("[VOD:ERR] {}", s.message)).await;
                }
                s.clone()
            };
            let mut terminal = terminal.lock().await;
            if terminal.len() >= TERMINAL_CACHE_LIMIT {
                terminal.pop_front();
            }
            terminal.push_back((terminal_job_id, final_status));
        });
        runtime.task = Some(task);
        Ok(self.status.read().await.clone())
    }

    pub async fn cancel(&self) -> Result<VodJobStatus> {
        let task = {
            let mut runtime = self.runtime.lock().await;
            if runtime.task.as_ref().is_some_and(|t| !t.is_finished()) {
                runtime.cancel.store(true, Ordering::SeqCst);
            }
            runtime.task.take()
        };
        {
            let mut s = self.status.write().await;
            if s.running {
                s.state = "CANCELLING".into();
                s.message = "외부 프로세스 종료 중…".into();
            }
        }
        if let Some(task) = task {
            let _ = task.await;
        }
        Ok(self.status.read().await.clone())
    }
}

