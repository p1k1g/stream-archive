use anyhow::{Context, Result, anyhow, bail};
use chrono::Utc;
use reqwest::{Response, header::SET_COOKIE};
use serde_json::Value;
use std::{collections::HashMap, fs, path::Path};
use url::Url;

pub(super) const CF_NAMES: &[&str] = &[
    "CloudFront-Key-Pair-Id",
    "CloudFront-Policy",
    "CloudFront-Signature",
];
pub(super) const LOGIN_COOKIE_NAMES: &[&str] = &[
    "AuthTicket",
    "BbsTicket",
    "UserTicket",
    "RDB",
    "PdboxTicket",
];

#[derive(Debug, Clone)]
pub(super) struct NetscapeCookie {
    pub(super) domain: String,
    pub(super) include_subdomains: bool,
    pub(super) path: String,
    pub(super) secure: bool,
    pub(super) expires: i64,
    pub(super) name: String,
    pub(super) value: String,
}

#[derive(Debug, Clone, Default)]
pub(super) struct CookieJar {
    pub(super) items: Vec<NetscapeCookie>,
}

impl CookieJar {
    pub(super) fn parse_file(path: &Path) -> Result<Self> {
        let text = fs::read_to_string(path)
            .with_context(|| format!("Cookie 파일 읽기 실패: {}", path.display()))?;
        let mut items = Vec::new();
        for raw in text.lines() {
            let line = raw.trim_end();
            if line.trim().is_empty() || (line.starts_with('#') && !line.starts_with("#HttpOnly_"))
            {
                continue;
            }
            let normalized = line.strip_prefix("#HttpOnly_").unwrap_or(line);
            let fields: Vec<&str> = normalized.splitn(7, '\t').collect();
            if fields.len() != 7 {
                continue;
            }
            items.push(NetscapeCookie {
                domain: fields[0].to_string(),
                include_subdomains: fields[1].eq_ignore_ascii_case("TRUE"),
                path: fields[2].to_string(),
                secure: fields[3].eq_ignore_ascii_case("TRUE"),
                expires: fields[4].parse().unwrap_or(0),
                name: fields[5].to_string(),
                value: fields[6].to_string(),
            });
        }
        if items.is_empty() {
            bail!("Cookie 파일이 Netscape 형식이 아니거나 비어 있습니다.");
        }
        Ok(Self { items })
    }

    pub(super) fn write_file(&self, path: &Path) -> Result<()> {
        let mut out = String::from(
            "# Netscape HTTP Cookie File\n# Generated by Stream Archive SOOP VOD; do not share.\n",
        );
        for c in &self.items {
            out.push_str(&format!(
                "{}\t{}\t{}\t{}\t{}\t{}\t{}\n",
                c.domain,
                if c.include_subdomains {
                    "TRUE"
                } else {
                    "FALSE"
                },
                c.path,
                if c.secure { "TRUE" } else { "FALSE" },
                c.expires,
                sanitize_cookie_field(&c.name),
                sanitize_cookie_field(&c.value)
            ));
        }
        fs::write(path, out).with_context(|| format!("Cookie 파일 저장 실패: {}", path.display()))
    }

    pub(super) fn header_for(&self, url: &str) -> Result<String> {
        let url = Url::parse(url)?;
        let host = url.host_str().unwrap_or("").to_ascii_lowercase();
        let path = url.path();
        let now = Utc::now().timestamp();
        let values = self
            .items
            .iter()
            .filter(|c| {
                if c.expires > 0 && c.expires < now {
                    return false;
                }
                if c.secure && url.scheme() != "https" {
                    return false;
                }
                let domain = c.domain.trim_start_matches('.').to_ascii_lowercase();
                let domain_ok = if c.include_subdomains || c.domain.starts_with('.') {
                    host == domain || host.ends_with(&format!(".{domain}"))
                } else {
                    host == domain
                };
                domain_ok && path.starts_with(if c.path.is_empty() { "/" } else { &c.path })
            })
            .map(|c| format!("{}={}", c.name, c.value))
            .collect::<Vec<_>>();
        Ok(values.join("; "))
    }

    pub(super) fn upsert(&mut self, cookie: NetscapeCookie) {
        self.items.retain(|c| {
            !(c.name.eq_ignore_ascii_case(&cookie.name)
                && c.domain.eq_ignore_ascii_case(&cookie.domain)
                && c.path == cookie.path)
        });
        self.items.push(cookie);
    }

    pub(super) fn remove_cloudfront(&mut self) {
        self.items
            .retain(|c| !c.name.to_ascii_lowercase().starts_with("cloudfront-"));
    }

    pub(super) fn has_cloudfront(&self) -> bool {
        let now = Utc::now().timestamp();
        CF_NAMES.iter().all(|name| {
            self.items.iter().any(|c| {
                c.name.eq_ignore_ascii_case(name)
                    && !c.value.is_empty()
                    && (c.expires <= 0 || c.expires >= now)
            })
        })
    }

    pub(super) fn has_login(&self) -> bool {
        LOGIN_COOKIE_NAMES.iter().any(|name| {
            self.items
                .iter()
                .any(|c| c.name.eq_ignore_ascii_case(name) && !c.value.is_empty())
        })
    }

    pub(super) fn repair_cloudfront_scope(&mut self, manifest_url: &str) -> Result<()> {
        let parsed = Url::parse(manifest_url)?;
        let host = parsed
            .host_str()
            .ok_or_else(|| anyhow!("manifest host 없음"))?
            .to_ascii_lowercase();
        let mut latest: HashMap<String, NetscapeCookie> = HashMap::new();
        let mut keep = Vec::new();
        for c in self.items.drain(..) {
            if c.name.to_ascii_lowercase().starts_with("cloudfront-") {
                latest.insert(c.name.to_ascii_lowercase(), c);
            } else {
                keep.push(c);
            }
        }
        for name in CF_NAMES {
            let mut c = latest
                .remove(&name.to_ascii_lowercase())
                .ok_or_else(|| anyhow!("private_auth 응답에 {name} Cookie가 없습니다."))?;
            c.domain = host.clone();
            c.include_subdomains = false;
            c.path = "/".into();
            c.secure = true;
            keep.push(c);
        }
        self.items = keep;
        Ok(())
    }
}

pub(super) fn collect_set_cookies(jar: &mut CookieJar, response: &Response, default_domain: &str) {
    for value in response.headers().get_all(SET_COOKIE).iter() {
        let Ok(text) = value.to_str() else {
            continue;
        };
        if let Some(cookie) = parse_set_cookie(text, default_domain) {
            jar.upsert(cookie);
        }
    }
}

pub(super) fn parse_set_cookie(text: &str, default_domain: &str) -> Option<NetscapeCookie> {
    let mut parts = text.split(';');
    let pair = parts.next()?.trim();
    let (name, value) = pair.split_once('=')?;
    let mut domain = default_domain.to_ascii_lowercase();
    let mut path = "/".to_string();
    let mut secure = false;
    let mut include_subdomains = false;
    for attr in parts {
        let attr = attr.trim();
        if attr.eq_ignore_ascii_case("secure") {
            secure = true;
        } else if let Some((key, value)) = attr.split_once('=') {
            if key.eq_ignore_ascii_case("domain") {
                domain = value.trim().to_ascii_lowercase();
                include_subdomains = domain.starts_with('.');
            } else if key.eq_ignore_ascii_case("path") {
                path = value.trim().to_string();
            }
        }
    }
    if domain.eq_ignore_ascii_case("sooplive.com") {
        domain = ".sooplive.com".into();
        include_subdomains = true;
    }
    Some(NetscapeCookie {
        domain,
        include_subdomains,
        path,
        secure,
        expires: 0,
        name: name.trim().to_string(),
        value: value.trim().to_string(),
    })
}

pub(super) fn collect_cloudfront_headers(
    jar: &mut CookieJar,
    response: &Response,
    manifest_url: &str,
) -> Result<()> {
    let parsed = Url::parse(manifest_url)?;
    let host = parsed.host_str().unwrap_or("").to_string();
    for value in response.headers().get_all(SET_COOKIE).iter() {
        let Ok(text) = value.to_str() else {
            continue;
        };
        let Some(pair) = text.split(';').next() else {
            continue;
        };
        let Some((name, value)) = pair.split_once('=') else {
            continue;
        };
        if name.to_ascii_lowercase().starts_with("cloudfront-") {
            jar.upsert(NetscapeCookie {
                domain: host.clone(),
                include_subdomains: false,
                path: "/".into(),
                secure: true,
                expires: 0,
                name: name.trim().into(),
                value: value.trim().trim_matches('"').into(),
            });
        }
    }
    Ok(())
}

pub(super) fn collect_cloudfront_json(jar: &mut CookieJar, value: &Value, manifest_url: &str) {
    let host = Url::parse(manifest_url)
        .ok()
        .and_then(|u| u.host_str().map(str::to_string))
        .unwrap_or_default();
    for name in CF_NAMES {
        let short = name.trim_start_matches("CloudFront-");
        let variants = [
            name.to_string(),
            name.replace('-', "_"),
            short.to_string(),
            short.replace('-', "_"),
        ];
        for key in variants {
            if let Some(v) = value
                .pointer(&format!("/data/{key}"))
                .and_then(Value::as_str)
                .or_else(|| value.get(&key).and_then(Value::as_str))
            {
                jar.upsert(NetscapeCookie {
                    domain: host.clone(),
                    include_subdomains: false,
                    path: "/".into(),
                    secure: true,
                    expires: 0,
                    name: (*name).into(),
                    value: v.into(),
                });
                break;
            }
        }
    }
}

fn sanitize_cookie_field(value: &str) -> String {
    value.replace(['\t', '\r', '\n'], "")
}
