async fn run_progress(program:&Path,args:&[String],part:usize,part_count:usize,status:&Arc<RwLock<VodJobStatus>>,cancel:&AtomicBool,logs:&LogBuffer)->Result<()> {
    let mut child=Command::new(program).args(args).stdin(Stdio::null()).stdout(Stdio::piped()).stderr(Stdio::piped()).kill_on_drop(false).spawn()?;
    let stdout=child.stdout.take().unwrap(); let stderr=child.stderr.take().unwrap();
    let err_lines=Arc::new(Mutex::new(Vec::<String>::new())); let err_copy=err_lines.clone();
    tokio::spawn(async move{let mut lines=BufReader::new(stderr).lines();while let Ok(Some(line))=lines.next_line().await{let mut v=err_copy.lock().await;v.push(line);if v.len()>30{v.remove(0);}}});
    let mut lines=BufReader::new(stdout).lines(); let re=Regex::new(r"(?P<p>\d+(?:\.\d+)?)%").unwrap();
    loop {
        if cancel.load(Ordering::SeqCst){stop_child(&mut child).await;return Ok(());}
        tokio::select! {
            line=lines.next_line()=>{if let Ok(Some(line))=line{if let Some(c)=re.captures(&line){if let Ok(p)=c["p"].parse::<f64>(){let mut s=status.write().await;s.percent=p;s.current_part=part;s.part_count=part_count;s.message=format!("PART {part}: {p:.1}%");}}}}
            _=tokio::time::sleep(Duration::from_millis(250))=>{}
        }
        if let Some(exit)=child.try_wait()?{if exit.success(){return Ok(());}let detail=err_lines.lock().await.iter().rev().take(12).cloned().collect::<Vec<_>>().into_iter().rev().collect::<Vec<_>>().join(" | ");bail!("yt-dlp exit={:?}: {}",exit.code(),redact(&detail));}
    }
}

