#[derive(Debug, Clone)]
struct NetscapeCookie {
    domain: String,
    include_subdomains: bool,
    path: String,
    secure: bool,
    expires: i64,
    name: String,
    value: String,
}

#[derive(Debug, Clone, Default)]
struct CookieJar { items: Vec<NetscapeCookie> }

impl CookieJar {
    fn parse_file(path: &Path) -> Result<Self> {
        let text = fs::read_to_string(path).with_context(|| format!("Cookie 파일 읽기 실패: {}", path.display()))?;
        let mut items = Vec::new();
        for raw in text.lines() {
            let line = raw.trim_end();
            if line.trim().is_empty() || (line.starts_with('#') && !line.starts_with("#HttpOnly_")) { continue; }
            let normalized = line.strip_prefix("#HttpOnly_").unwrap_or(line);
            let fields: Vec<&str> = normalized.splitn(7, '\t').collect();
            if fields.len() != 7 { continue; }
            items.push(NetscapeCookie {
                domain: fields[0].to_string(), include_subdomains: fields[1].eq_ignore_ascii_case("TRUE"),
                path: fields[2].to_string(), secure: fields[3].eq_ignore_ascii_case("TRUE"),
                expires: fields[4].parse().unwrap_or(0), name: fields[5].to_string(), value: fields[6].to_string(),
            });
        }
        if items.is_empty() { bail!("Cookie 파일이 Netscape 형식이 아니거나 비어 있습니다."); }
        Ok(Self { items })
    }

    fn write_file(&self, path: &Path) -> Result<()> {
        let mut out = String::from("# Netscape HTTP Cookie File\n# Generated by SOOP Rust VOD; do not share.\n");
        for c in &self.items {
            out.push_str(&format!("{}\t{}\t{}\t{}\t{}\t{}\t{}\n",
                c.domain, if c.include_subdomains {"TRUE"} else {"FALSE"}, c.path,
                if c.secure {"TRUE"} else {"FALSE"}, c.expires, sanitize_cookie_field(&c.name), sanitize_cookie_field(&c.value)));
        }
        fs::write(path, out).with_context(|| format!("Cookie 파일 저장 실패: {}", path.display()))
    }

    fn header_for(&self, url: &str) -> Result<String> {
        let url = Url::parse(url)?;
        let host = url.host_str().unwrap_or("").to_ascii_lowercase();
        let path = url.path();
        let now = Utc::now().timestamp();
        let values = self.items.iter().filter(|c| {
            if c.expires > 0 && c.expires < now { return false; }
            if c.secure && url.scheme() != "https" { return false; }
            let domain = c.domain.trim_start_matches('.').to_ascii_lowercase();
            let domain_ok = if c.include_subdomains || c.domain.starts_with('.') { host == domain || host.ends_with(&format!(".{domain}")) } else { host == domain };
            domain_ok && path.starts_with(if c.path.is_empty() { "/" } else { &c.path })
        }).map(|c| format!("{}={}", c.name, c.value)).collect::<Vec<_>>();
        Ok(values.join("; "))
    }

    fn upsert(&mut self, cookie: NetscapeCookie) {
        self.items.retain(|c| !(c.name.eq_ignore_ascii_case(&cookie.name) && c.domain.eq_ignore_ascii_case(&cookie.domain) && c.path == cookie.path));
        self.items.push(cookie);
    }

    fn remove_cloudfront(&mut self) { self.items.retain(|c| !c.name.to_ascii_lowercase().starts_with("cloudfront-")); }
    fn has_cloudfront(&self) -> bool { CF_NAMES.iter().all(|name| self.items.iter().any(|c| c.name.eq_ignore_ascii_case(name) && !c.value.is_empty())) }
    fn has_login(&self) -> bool { LOGIN_COOKIE_NAMES.iter().any(|name| self.items.iter().any(|c| c.name.eq_ignore_ascii_case(name) && !c.value.is_empty())) }

    fn cloudfront_header(&self) -> Result<String> {
        let mut map = HashMap::new();
        for c in &self.items { if CF_NAMES.iter().any(|n| c.name.eq_ignore_ascii_case(n)) { map.insert(c.name.to_ascii_lowercase(), c.value.clone()); } }
        let mut parts = Vec::new();
        for name in CF_NAMES {
            let value = map.get(&name.to_ascii_lowercase()).ok_or_else(|| anyhow!("{name} Cookie가 없습니다."))?;
            parts.push(format!("{name}={value}"));
        }
        Ok(parts.join("; "))
    }

    fn repair_cloudfront_scope(&mut self, manifest_url: &str) -> Result<()> {
        let host = Url::parse(manifest_url)?.host_str().ok_or_else(|| anyhow!("manifest host 없음"))?.to_ascii_lowercase();
        let mut latest: HashMap<String, NetscapeCookie> = HashMap::new();
        let mut keep = Vec::new();
        for c in self.items.drain(..) {
            if c.name.to_ascii_lowercase().starts_with("cloudfront-") { latest.insert(c.name.to_ascii_lowercase(), c); } else { keep.push(c); }
        }
        for name in CF_NAMES {
            let mut c = latest.remove(&name.to_ascii_lowercase()).ok_or_else(|| anyhow!("private_auth 응답에 {name} Cookie가 없습니다."))?;
            c.domain = host.clone(); c.include_subdomains = false; c.path = "/".into(); c.secure = true;
            keep.push(c);
        }
        self.items = keep;
        Ok(())
    }
}

struct JobRuntime { task: Option<JoinHandle<()>>, cancel: Arc<AtomicBool> }

pub struct VodManager {
    backend_dir: PathBuf,
    logs: LogBuffer,
    runtime: Mutex<JobRuntime>,
    status: Arc<RwLock<VodJobStatus>>,
}

impl VodManager {
    pub fn new(backend_dir: PathBuf, logs: LogBuffer) -> Self {
        Self { backend_dir, logs, runtime: Mutex::new(JobRuntime { task: None, cancel: Arc::new(AtomicBool::new(false)) }), status: Arc::new(RwLock::new(VodJobStatus::default())) }
    }

    pub async fn status(&self) -> VodJobStatus {
        let finished = { self.runtime.lock().await.task.as_ref().is_some_and(|t| t.is_finished()) };
        if finished { self.runtime.lock().await.task.take(); }
        self.status.read().await.clone()
    }

    pub async fn analyze(&self, req: VodAnalyzeRequest) -> Result<VodJobStatus> {
        self.start_job(VodJobKind::Analyze(req)).await
    }

    pub async fn download(&self, req: VodDownloadRequest) -> Result<VodJobStatus> {
        self.start_job(VodJobKind::Download(req)).await
    }

    async fn start_job(&self, kind: VodJobKind) -> Result<VodJobStatus> {
        let mut runtime = self.runtime.lock().await;
        if runtime.task.as_ref().is_some_and(|t| !t.is_finished()) { bail!("다른 VOD 작업이 이미 실행 중입니다."); }
        runtime.task.take();
        let cancel = Arc::new(AtomicBool::new(false));
        runtime.cancel = cancel.clone();
        let backend = self.backend_dir.clone();
        let logs = self.logs.clone();
        let status = self.status.clone();
        let job_id = Uuid::new_v4().to_string();
        {
            let mut s = status.write().await;
            *s = VodJobStatus { state: "STARTING".into(), running: true, job_id: Some(job_id.clone()), message: "VOD 작업 준비 중…".into(), started_at: Some(Utc::now().to_rfc3339()), ..Default::default() };
        }
        let task = tokio::spawn(async move {
            let result = match kind {
                VodJobKind::Analyze(req) => run_analysis(&backend, req, &logs, &status, &cancel).await.map(|_| ()),
                VodJobKind::Download(req) => run_download(&backend, req, &logs, &status, &cancel).await,
            };
            let mut s = status.write().await;
            s.running = false;
            s.finished_at = Some(Utc::now().to_rfc3339());
            if cancel.load(Ordering::SeqCst) {
                s.state = "CANCELLED".into(); s.message = "VOD 작업이 취소되었습니다.".into();
                logs.push("[VOD] job cancelled").await;
            } else if let Err(err) = result {
                s.state = "FAILED".into(); s.message = redact(&format!("{err:#}"));
                logs.push(format!("[VOD:ERR] {}", s.message)).await;
            }
        });
        runtime.task = Some(task);
        Ok(self.status.read().await.clone())
    }

    pub async fn cancel(&self) -> Result<VodJobStatus> {
        let runtime = self.runtime.lock().await;
        if runtime.task.as_ref().is_some_and(|t| !t.is_finished()) { runtime.cancel.store(true, Ordering::SeqCst); }
        drop(runtime);
        let mut s = self.status.write().await;
        if s.running { s.state = "CANCELLING".into(); s.message = "외부 프로세스 종료 중…".into(); }
        Ok(s.clone())
    }
}

enum VodJobKind { Analyze(VodAnalyzeRequest), Download(VodDownloadRequest) }

async fn run_analysis(backend: &Path, req: VodAnalyzeRequest, logs: &LogBuffer, status: &Arc<RwLock<VodJobStatus>>, cancel: &AtomicBool) -> Result<VodAnalysisView> {
    validate_url(&req.vod_url)?;
    validate_retries(req.max_retries)?;
    set_status(status, "ANALYZING", "VOD 분석 중…").await;
    let tools = resolve_tools(backend, &req.yt_dlp_path, &req.ffmpeg_path)?;
    let job_dir = job_dir(backend)?;
    let mut jar = init_cookie(backend, &tools, &req.vod_url, &req.cookie_mode, &req.cookie_file, &req.browser_name, &job_dir, cancel, logs).await?;
    let cookie_file = job_dir.join("cookies.txt");
    jar.write_file(&cookie_file)?;
    let mut metadata = get_metadata(&tools, &req.vod_url, &cookie_file, cancel, logs).await?;
    complete_metadata_from_api(&req.vod_url, &mut metadata, &jar).await.ok();
    let first = metadata.entries.first().ok_or_else(|| anyhow!("VOD PART를 찾지 못했습니다."))?.manifest_url.clone();
    if first.is_empty() { bail!("첫 번째 PART manifest URL이 없습니다."); }
    if !jar.has_cloudfront() {
        refresh_authorization(&req.vod_url, &metadata.streamer_id, &first, &mut jar, 1, logs).await?;
    } else { jar.repair_cloudfront_scope(&first)?; }
    let qualities = probe_manifest(&req.vod_url, &first, &jar).await?;
    jar.write_file(&cookie_file)?;
    let view = analysis_view(&req.vod_url, &metadata, qualities);
    {
        let mut s = status.write().await;
        s.state = "READY".into(); s.running = false; s.message = "분석 완료 · PART와 화질을 선택하세요.".into(); s.part_count = view.part_count; s.analysis = Some(view.clone()); s.percent = 100.0; s.finished_at = Some(Utc::now().to_rfc3339());
    }
    logs.push(format!("[VOD] analysis ready title={} streamer={} parts={}", metadata.title, metadata.streamer, metadata.entries.len())).await;
    cleanup_job_dir(&job_dir);
    Ok(view)
}

async fn run_download(backend: &Path, req: VodDownloadRequest, logs: &LogBuffer, status: &Arc<RwLock<VodJobStatus>>, cancel: &AtomicBool) -> Result<()> {
    validate_url(&req.vod_url)?; validate_retries(req.max_retries)?;
    if !req.quality.is_empty() && !Regex::new(r"^best(?:\[height<=\d+\])?$").unwrap().is_match(&req.quality) { bail!("지원하지 않는 VOD 화질 선택입니다."); }
    let tools = resolve_tools(backend, &req.yt_dlp_path, &req.ffmpeg_path)?;
    let output_dir = PathBuf::from(&req.output_directory);
    if req.output_directory.trim().is_empty() { bail!("VOD 출력 폴더가 비어 있습니다."); }
    fs::create_dir_all(&output_dir)?;
    let job_dir = job_dir(backend)?;
    let mut jar = init_cookie(backend, &tools, &req.vod_url, &req.cookie_mode, &req.cookie_file, &req.browser_name, &job_dir, cancel, logs).await?;
    let cookie_file = job_dir.join("cookies.txt"); jar.write_file(&cookie_file)?;
    let mut metadata = get_metadata(&tools, &req.vod_url, &cookie_file, cancel, logs).await?;
    complete_metadata_from_api(&req.vod_url, &mut metadata, &jar).await.ok();
    let selected = resolve_parts(&req.parts, metadata.entries.len())?;
    {
        let mut s = status.write().await; s.state="DOWNLOADING".into(); s.part_count=metadata.entries.len(); s.message="VOD 다운로드 시작".into();
        s.analysis=Some(analysis_view(&req.vod_url, &metadata, vec![VodQualityOption{value:"best".into(),label:"최고 화질 (자동)".into()}]));
    }
    let mut files = Vec::new();
    for part in selected {
        if cancel.load(Ordering::SeqCst) { cleanup_job_dir(&job_dir); return Ok(()); }
        let mut last_error = String::new();
        let output = collision_path(&output_dir, &format!("{}_{}_{:02}", metadata.date, safe_name(&metadata.streamer), part), ".mp4")?;
        for attempt in 1..=req.max_retries {
            if cancel.load(Ordering::SeqCst) { cleanup_incomplete(&output); cleanup_job_dir(&job_dir); return Ok(()); }
            if attempt > 1 {
                jar = renew_base_cookie(backend, &tools, &req.vod_url, &req.cookie_mode, &req.cookie_file, &req.browser_name, &job_dir, cancel, logs).await?;
                jar.write_file(&cookie_file)?;
            }
            {
                let mut s=status.write().await; s.current_part=part; s.state="REFRESHING".into(); s.message=format!("PART {part} 최신 URL/인증 갱신 중 ({attempt}/{})", req.max_retries);
            }
            let mut refreshed = get_metadata(&tools, &req.vod_url, &cookie_file, cancel, logs).await?;
            complete_metadata_from_api(&req.vod_url, &mut refreshed, &jar).await.ok();
            let url = refreshed.entries.get(part-1).map(|e| e.manifest_url.clone()).filter(|s| !s.is_empty()).or_else(|| metadata.entries.get(part-1).map(|e| e.manifest_url.clone())).ok_or_else(|| anyhow!("PART {part} URL이 없습니다."))?;
            if !(attempt == 1 && jar.has_cloudfront()) {
                jar.remove_cloudfront();
                if let Err(err)=refresh_authorization(&req.vod_url, &refreshed.streamer_id, &url, &mut jar, attempt, logs).await { last_error=err.to_string(); sleep_retry(attempt, cancel).await; continue; }
            } else { jar.repair_cloudfront_scope(&url)?; }
            if let Err(err)=probe_manifest(&req.vod_url, &url, &jar).await { last_error=err.to_string(); sleep_retry(attempt, cancel).await; continue; }
            jar.write_file(&cookie_file)?;
            {
                let mut s=status.write().await; s.state="DOWNLOADING".into(); s.message=format!("PART {part}/{} 다운로드 중…", metadata.entries.len());
            }
            match download_part(&tools, &req, &cookie_file, &url, &output, part, metadata.entries.len(), status, cancel, logs).await {
                Ok(()) => { files.push(output.clone()); last_error.clear(); break; }
                Err(err) => { last_error=err.to_string(); cleanup_incomplete(&output); logs.push(format!("[VOD:WARN] PART {part} retry {attempt}/{}: {}", req.max_retries, redact(&last_error))).await; sleep_retry(attempt, cancel).await; }
            }
        }
        if !last_error.is_empty() && !output.is_file() { cleanup_job_dir(&job_dir); bail!("PART {part} 다운로드 실패: {last_error}"); }
    }
    if cancel.load(Ordering::SeqCst) { cleanup_job_dir(&job_dir); return Ok(()); }
    let final_file = if files.len() > 1 && req.merge { merge_parts(&tools, &metadata, &files, &output_dir, status, cancel, logs).await? } else { files.first().cloned().ok_or_else(|| anyhow!("다운로드된 PART가 없습니다."))? };
    {
        let mut s=status.write().await; s.state="COMPLETED".into(); s.running=false; s.message="VOD 다운로드가 완료되었습니다.".into(); s.output_file=Some(final_file.display().to_string()); s.percent=100.0; s.finished_at=Some(Utc::now().to_rfc3339());
    }
    logs.push(format!("[VOD] completed file={}", final_file.display())).await;
    cleanup_job_dir(&job_dir);
    Ok(())
}

async fn init_cookie(backend:&Path, tools:&Tools, vod_url:&str, mode:&str, cookie_file:&str, browser:&str, job_dir:&Path, cancel:&AtomicBool, logs:&LogBuffer)->Result<CookieJar>{
    match mode.to_ascii_uppercase().as_str() {
        "SOOP_LOGIN" => login_cookie(backend, vod_url, logs).await,
        "FILE" => CookieJar::parse_file(Path::new(cookie_file)),
        "BROWSER" => {
            let target=job_dir.join("browser-cookies.txt");
            run_simple_process(&tools.yt_dlp, &["--cookies-from-browser",browser,"--cookies",target.to_string_lossy().as_ref(),"--skip-download",vod_url], cancel, logs, "yt-dlp cookie").await?;
            CookieJar::parse_file(&target)
        }
        other => bail!("지원하지 않는 Cookie 모드입니다: {other}"),
    }
}

async fn renew_base_cookie(backend:&Path, tools:&Tools, vod_url:&str, mode:&str, cookie_file:&str, browser:&str, job_dir:&Path, cancel:&AtomicBool, logs:&LogBuffer)->Result<CookieJar>{
    init_cookie(backend, tools, vod_url, mode, cookie_file, browser, job_dir, cancel, logs).await
}

async fn login_cookie(backend:&Path, vod_url:&str, logs:&LogBuffer)->Result<CookieJar>{
    let settings=read_ini(&backend.join("SOOP_LIVE_SETTING.ini"))?;
    let username=settings.get("SOOP_USERNAME").cloned().unwrap_or_default();
    let password=unprotect_secret(settings.get("SOOP_PASSWORD").map(String::as_str).unwrap_or(""), "SOOP_PASSWORD")?;
    if username.is_empty()||password.is_empty(){bail!("SOOP 아이디와 비밀번호를 먼저 설정해 주세요.");}
    let client=http_client()?;
    let response=client.post("https://login.sooplive.com/app/LoginAction.php").header(REFERER,"https://www.sooplive.com/").form(&[("szWork","login"),("szType","json"),("szUid",username.as_str()),("szPassword",password.as_str()),("isSaveId","true"),("isSavePw","false"),("isSaveJoin","false"),("isLoginRetain","Y")]).send().await?;
    let mut jar=CookieJar::default(); collect_set_cookies(&mut jar,&response,"sooplive.com");
    let value:Value=response.error_for_status()?.json().await?;
    if value.get("RESULT").and_then(Value::as_i64)!=Some(1){bail!("SOOP 로그인 실패 RESULT={:?}",value.get("RESULT"));}
    let cookie=jar.header_for("https://afevent2.sooplive.com/")?;
    let verify=client.get("https://afevent2.sooplive.com/api/get_private_info.php").header(REFERER,"https://www.sooplive.com/").header(COOKIE,cookie).send().await?;
    collect_set_cookies(&mut jar,&verify,"sooplive.com");
    let auth:Value=verify.error_for_status()?.json().await?;
    if auth.pointer("/CHANNEL/LOGIN_ID").and_then(Value::as_str).unwrap_or("").is_empty(){bail!("SOOP 로그인 검증에 실패했습니다.");}
    let cookie=jar.header_for(vod_url)?;
    let mut req=client.get(vod_url).header(REFERER,"https://vod.sooplive.com/"); if !cookie.is_empty(){req=req.header(COOKIE,cookie);}
    let visit=req.send().await?; collect_set_cookies(&mut jar,&visit,"sooplive.com"); let _=visit.error_for_status()?;
    jar.remove_cloudfront();
    logs.push(format!("[VOD:AUTH] SOOP login session ready: {username}")).await;
    Ok(jar)
}

async fn refresh_authorization(vod_url:&str, streamer_id:&str, manifest_url:&str, jar:&mut CookieJar, attempt:u32, logs:&LogBuffer)->Result<()> {
    jar.remove_cloudfront();
    let title_no=title_no(vod_url)?;
    let client=http_client()?;
    let cookie=jar.header_for("https://live.sooplive.com/api/private_auth.php")?;
    let response=client.post("https://live.sooplive.com/api/private_auth.php").header(REFERER,vod_url).header("Origin","https://vod.sooplive.com").header("Accept","application/json, text/plain, */*").header(COOKIE,cookie).form(&[("type","vod"),("strm_id",streamer_id),("title_no",title_no.as_str()),("url",manifest_url)]).send().await?;
    collect_cloudfront_headers(jar,&response,manifest_url)?;
    let text=response.error_for_status()?.text().await?;
    let value:Value=serde_json::from_str(&text).unwrap_or(Value::Null);
    if value.get("result").and_then(Value::as_i64)!=Some(1){
        let code=value.pointer("/data/code").and_then(Value::as_i64).map(|v|v.to_string()).unwrap_or_default();
        let msg=value.pointer("/data/message").and_then(Value::as_str).unwrap_or("private_auth 실패");
        bail!("private_auth {code}: {msg}");
    }
    collect_cloudfront_json(jar,&value,manifest_url);
    jar.repair_cloudfront_scope(manifest_url)?;
    logs.push(format!("[VOD:AUTH] private_auth OK attempt={attempt} host={}",Url::parse(manifest_url)?.host_str().unwrap_or(""))).await;
    Ok(())
}

async fn probe_manifest(vod_url:&str,url:&str,jar:&CookieJar)->Result<Vec<VodQualityOption>>{
    let client=http_client()?; let cookie=jar.cloudfront_header()?;
    let response=client.get(url).header(REFERER,vod_url).header("Origin","https://vod.sooplive.com").header(COOKIE,cookie).send().await?;
    let status=response.status(); let text=response.text().await.unwrap_or_default();
    if !status.is_success(){bail!("manifest authorization check failed: HTTP {status}, host={}",Url::parse(url)?.host_str().unwrap_or(""));}
    let mut heights=Regex::new(r"RESOLUTION=\d+x(?P<h>\d+)").unwrap().captures_iter(&text).filter_map(|c|c.name("h")?.as_str().parse::<u32>().ok()).collect::<Vec<_>>();
    heights.sort_unstable_by(|a,b|b.cmp(a)); heights.dedup();
    let mut out=vec![VodQualityOption{value:"best".into(),label:"최고 화질 (자동)".into()}];
    for h in heights {out.push(VodQualityOption{value:format!("best[height<={h}]"),label:format!("{h}p")});}
    Ok(out)
}

